# 2. Count the occurence of 20 in the tuple. t = (2, 90, 64, 20, 16, 20, 9, 20).

t = (2, 90, 64, 20, 16, 20, 9, 20)
print(t.count(20))

# 4. Find the index of 42 in the tuple. t = (56, 7.3, 'Soura', 42, True).

t = (56, 7.3, 'Soura', 42, True)
print(t.index(42))

# 5. Find the value in index 3, in the same tuple of question 4.

t = (56, 7.3, 'Soura', 42, True)
