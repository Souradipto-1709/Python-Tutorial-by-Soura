# Python Operators 
# ------------------------------

# Operators are like special symbols in python, which are used to perform operations on values or variables.
# There are 4 types of operators in Python:=

# Arithmetic Operators: +, -, *, /, //, ** etc.
# This type of operators are used to perform mathematical calculations with different values or variables.

# Eg:
a = 10
b = 5

print(a+b) # Addition
print(a-b) # Subtraction
print(a*b) # Multiplication
print(a/b) # Division 
print(a//b) # Floor Division
print(a**b) # Power
print(a%b) # Modulus

# Output:
# 15
# 5
# 50
# 2.0
# 2
# 100000
# 0

# -------------------------------

# Assignment Operators: =, ,+=, -= etc.
# This type of operators are used to assign and update values to variables.

# Eg:
a = 10
print(a)

b = 5
b+=5
print(b)

c = 15
c-=5
print(c)

# Output:
# 10
# 10
# 10

# --------------------------------

# Comparision Operators: ==, >, >=, <, != etc
# This type of operators compares 2 values or variables, and give the output in True or False.

# Eg:
x = 10
y = 5

print(x == y)  # Equal to
print(x != y)  # Not equal to
print(x > y)   # Greater than
print(x < y)   # Less than
print(x >= y)  # Greater than equal to
print(x <= y)  # Less than equal to

# Output:
# False
# True
# True
# False
# True
# False

# -------------------------------

# Boolean Operators: and, or, not etc.
# This type of operators are used to combine two or more conditions or reverse the output, using specific logical rules, and gives output in True or False.

# Eg:
# and Operator: Returns true only if both the values are true.

print(True and True)
print(True and False)
print(False and True)
print(False and False)

# Output:
# True
# False
# False
# True

# or Operator: Returns true if atleast one condition is true among the others.

print(True or True)
print(True or False)
print(False or True)
print(False and False)

# Output:
# True
# True
# True
# False

# not Operator: Returns the reversed Boolean value.

print(not True)
print(not False)

# Output:
# False
# True


