# Now, let us practice some basic operations and programs using Python Operators:
 
# 1
n1 = int(input('Enter no 1: '))
n2 = int(input('Enter no 2: '))
print('Sum is', n1+n2)  # Arithmetic Operators(+)

# 2
n1 = int(input('Enter no 1: '))
n2 = int(input('Enter no 2: '))
print('Modulus is', n1%n2) # Arithmetic Operators(%)

# 3
a = int(input('Enter no: '))
a+=4
print(a) # Assignment Operators

# 4
b = int(input('Enter no: '))
b-=7
print(b) # Assignment Operators

# 5
a = int(input('Enter no: '))
print(a>=8) # Comparision Operators

# 6
b = int(input('Enter no: '))
print(b!=10) # Comparision Operators

# 7
a = int(input('Enter no 1: '))
b = int(input('Enter no 2: '))
if(a==2 and b==9):
    print('True')
else:
    print('False') # A simple if-else conditional statement using Boolean Operator(and).
    
# 8
a = int(input('Enter no: '))
if not(a==10):
    print('True')
else:
    print('False') # A simple if-else conditional statement using Boolean Operator(not).


